package com.courtsync.courts.court;

/**
 * Net height standard for play. Independent of surface (any net height can be set
 * on any surface). MENS and WOMENS are the official heights; COED games typically
 * use a height between them. Stored as its name string.
 */
public enum NetHeight {
    MENS,
    WOMENS,
    COED
}
